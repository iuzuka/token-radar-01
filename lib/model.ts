// Token Radar model: comps-calibrated implied values for pre-token protocols.
//
// The snapshot is the sealed DefiLlama universe. The board ranks every protocol that
// still records no token, by what its launch would be worth. The worth is not a flat
// multiple of TVL: it is calibrated from the protocols that already trade. For each
// category the model takes the median market-cap-to-TVL ratio of the live-token
// protocols in that category, so a DEX is priced like a DEX and a lender like a
// lender, and a category with too few live comparables falls back to the global
// median. Growth, maturity and chain breadth then move the multiple up or down.
//
//   multiple     = median(mcap / tvl) over live-token protocols in the category
//                  (global median when the category has fewer than 3 comparables),
//                  clamped to [0.05, 2.0]
//   base         = tvl_usd * multiple
//   growth       = clamp(change_7d, -60, 120) per cent
//   growthMult   = 1 + (growth / 100) * 0.5
//   maturity     = 0.6 + min(age_days, 1095) / 1095 * 0.4   (age unknown: 365 days)
//   breadth      = 1 + 0.03 * min(chains - 1, 5)
//   implied      = max(1, round(base * growthMult * maturity * breadth))
//
// The board covers the snapshot's watchlist in full (the floor, never a ceiling)
// plus every other rankable pre-token protocol below the floor, strongest first.
// Live-token protocols are kept apart and shown at the market's own values, never
// mixed into the ranked board. No protocol name is ever special-cased: the same
// functions score every row, and the same run on the same snapshot writes the same
// bytes.

// The farm plan lives in its own module so the model stays about scoring.
import { farmSteps, stepText } from './farm.ts';

/** One protocol entry of the sealed snapshot: exactly the ten fields it carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole sealed snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_step: number;
  breadth_max_chains: number;
  multiple_floor: number;
  multiple_cap: number;
  min_category_comps: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  breadth_step: 0.03,
  breadth_max_chains: 5,
  multiple_floor: 0.05,
  multiple_cap: 2.0,
  min_category_comps: 3,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

/** How many live-token protocols the Live view carries, by market cap. */
export const LIVE_ROWS = 24;

/** One category's calibration: the median multiple and how many live protocols set it. */
export interface CategoryComp {
  category: string;
  multiple: number;
  comps: number;
  median_ratio: number;
}

/** The calibration table: one entry per category that has live protocols, plus the global row. */
export interface Calibration {
  by_category: CategoryComp[];
  global_multiple: number;
  global_comps: number;
}

/** A farm step: the action, what it costs, and how long it takes. */
export interface FarmStep {
  text: string;
  cost: string;
  time: string;
}

/** One row of board.json: the ranked board's row. */
export interface BoardRow {
  rank: number;
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
  token_status: 'pre-token';
  age_days: number | null;
  implied_value_usd: number;
  model: {
    category_multiple: number;
    category_comps: number;
    growth_pct: number;
    growth_multiplier: number;
    maturity_multiplier: number;
    breadth_multiplier: number;
    age_days: number | null;
  };
  farm_steps: string[];
}

